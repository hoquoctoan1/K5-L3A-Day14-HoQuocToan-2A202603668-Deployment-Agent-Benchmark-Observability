"""Capture real Prometheus/Jaeger evidence; run while the lab stack is up.

python capture_evidence.py --docker <path-to-docker>
No screenshots are generated by this utility: capture the actual service UIs too.
API reference: https://www.jaegertracing.io/docs/2.23/architecture/apis/
"""
import argparse
from datetime import datetime, timedelta, timezone
import json
from pathlib import Path
import subprocess
import urllib.parse
import urllib.request
import urllib.error


def get_json(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        return json.load(response)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--docker", default="docker")
    parser.add_argument("--out-dir", help="Separate evidence directory for an additional run")
    args = parser.parse_args()
    production = Path(__file__).resolve().parent
    reports = Path(args.out_dir).resolve() if args.out_dir else production.parents[2] / "reports"
    reports.mkdir(parents=True, exist_ok=True)
    evidence = {"captured_at_utc": datetime.now(timezone.utc).isoformat(), "queries": {}}
    evidence["grafana_health"] = get_json("http://localhost:3000/api/health")
    evidence["grafana_dashboards"] = get_json("http://localhost:3000/api/search?type=dash-db")
    try:
        with urllib.request.urlopen("http://localhost:8080/metrics", timeout=5) as response:
            evidence["public_metrics_status"] = response.status
    except urllib.error.HTTPError as exc:
        evidence["public_metrics_status"] = exc.code
    queries = {
        "rps_by_instance": 'sum by(instance)(rate(http_requests_total{job="agent",route="/ask"}[1m]))',
        "p95_seconds": 'histogram_quantile(0.95,sum by(le)(rate(http_request_duration_seconds_bucket{job="agent",route="/ask"}[1m])))',
        "avg_seconds": 'sum(rate(http_request_duration_seconds_sum{job="agent",route="/ask"}[1m]))/sum(rate(http_request_duration_seconds_count{job="agent",route="/ask"}[1m]))',
        "tokens_per_second": 'sum by(type)(rate(llm_tokens_total{job="agent"}[1m]))',
    }
    for name, query in queries.items():
        evidence["queries"][name] = get_json("http://localhost:9090/api/v1/query?" + urllib.parse.urlencode({"query": query}))
    evidence["alerts"] = get_json("http://localhost:9090/api/v1/alerts")
    now = datetime.now(timezone.utc)
    query = urllib.parse.urlencode({
        "query.service_name": "observable-agent", "query.search_depth": "200",
        "query.start_time_min": (now - timedelta(hours=1)).isoformat(),
        "query.start_time_max": now.isoformat(),
    })
    # Jaeger 2.23 exposes the stable OTLP-based /api/v3 API.
    payload = get_json("http://localhost:16686/api/v3/traces?" + query)
    grouped = {}
    for resource in payload.get("result", {}).get("resourceSpans", []):
        for scope in resource.get("scopeSpans", []):
            for span in scope.get("spans", []):
                grouped.setdefault(span["traceId"], []).append(span)
    traces = [{"trace_id": trace_id, "spans": spans} for trace_id, spans in grouped.items()]
    if not traces:
        raise RuntimeError("Jaeger returned no traces")
    duration = lambda trace: max(int(s["endTimeUnixNano"]) for s in trace["spans"]) - min(int(s["startTimeUnixNano"]) for s in trace["spans"])
    slow = max(traces, key=duration)
    errors = [t for t in traces if any(s.get("status", {}).get("code") == 2 for s in t["spans"])]
    if not errors:
        raise RuntimeError("Jaeger returned no error trace; generate failures before capturing")
    selected = {"slow": slow, "error": max(errors, key=duration)}
    logs = subprocess.run([args.docker, "compose", "-p", "k5-day14-observability", "logs", "--no-color", "agent"],
                          cwd=production, capture_output=True, text=True, encoding="utf-8", check=True).stdout
    for name, trace in selected.items():
        (reports / f"jaeger_{name}_trace.json").write_text(json.dumps(trace, indent=2, ensure_ascii=False), encoding="utf-8")
        matching = [line for line in logs.splitlines() if trace["trace_id"] in line]
        children = [s for s in trace["spans"] if s["name"].startswith("chat ") or s["name"] == "agent.retrieve_context"]
        evidence[f"{name}_trace"] = {"trace_id": trace["trace_id"], "duration_ms": duration(trace) / 1_000_000,
                                     "matching_logs": matching,
                                     "longest_processing_span": max(children, key=lambda s: int(s["endTimeUnixNano"]) - int(s["startTimeUnixNano"]))}
        if not matching:
            raise RuntimeError(f"Trace {trace['trace_id']} has no matching agent log")
    (reports / "observability_evidence.json").write_text(json.dumps(evidence, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps({k: evidence[k]["trace_id"] for k in ("slow_trace", "error_trace")}, indent=2))


if __name__ == "__main__":
    main()
